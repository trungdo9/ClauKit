/**
 * Converts a scanned `.claude/` tree into OpenAI Codex CLI's conventions.
 *
 * Mapping (confirmed against developers.openai.com/codex docs, 2026-08):
 *   .claude/skills/ (all)         -> .codex/skills/ (identical SKILL.md format, verbatim copy)
 *   .claude/agents/ (all *.md)    -> .codex/agents/<name>.toml (Codex custom subagents: name/description/developer_instructions)
 *   .claude/commands/ (all *.md)  -> .codex/skills/<ns>-<name>/SKILL.md (custom prompts are deprecated in favor of Skills;
 *                                    prompts also live in ~/.codex/prompts, NOT the repo, so they wouldn't travel with the project) +
 *                                    a companion agents/openai.yaml with allow_implicit_invocation: false — a Claude Code
 *                                    command only ever runs when the user types `/ns:name`, never on Claude's own judgment,
 *                                    so its Codex equivalent should only fire on explicit `$ns-name` too, not on Codex's
 *                                    own guess that the description matches. Skills copied straight from .claude/skills/
 *                                    keep Codex's default (implicit-invocation-eligible) — those were already designed
 *                                    to be triggered contextually, unlike a command.
 *   CLAUDE.md + .claude/workflows -> root AGENTS.md (lean index) + .codex/workflows/*.md (full text, referenced not inlined —
 *                                    combined instructions are capped at project_doc_max_bytes, 32 KiB by default, and this
 *                                    repo's CLAUDE.md + workflows alone total ~75 KiB)
 *   .claude/mcp.json             -> .codex/config.toml [mcp_servers.*]
 *   .claude/hooks/, settings.json -> NOT PORTABLE (no Codex equivalent) — reported as a warning, not written
 */

const path = require("path");
const { tomlBasicString, tomlMultilineBody, tomlStringArray } = require("./toml");
const { rewriteSkillRefs } = require("./link-rewrite");
const { newSummary, writeFileSafe, copyDirSafe } = require("./write-safe");

const DISPLAY_PREFIX = ".codex/skills/";

function agentToml(agent) {
  const lines = [];
  lines.push(`name = ${tomlBasicString(agent.name)}`);
  if (agent.data.description) lines.push(`description = ${tomlBasicString(agent.data.description)}`);
  if (agent.data.model) lines.push(`model = ${tomlBasicString(agent.data.model)}`);
  lines.push("");
  const body = rewriteSkillRefs(agent.body, { displayPrefix: DISPLAY_PREFIX, hrefBase: "../skills/" });
  lines.push(`developer_instructions = ${tomlMultilineBody(body)}`);
  return lines.join("\n");
}

function commandSkillMd(cmd) {
  const skillName = `${cmd.ns}-${cmd.name}`;
  const front = [`---`, `name: ${skillName}`, `description: ${cmd.data.description || `Port of ClauKit's /${cmd.ns}:${cmd.name} command`}`, `---`, ``];
  const trigger = [
    `## Trigger`,
    ``,
    `This was a Claude Code slash command (\`/${cmd.ns}:${cmd.name}\`) — invoke it the same explicit way in Codex CLI:` ,
    `\`$${skillName} <your request>\` (or \`/skills\` to pick it from a list). It ships with` ,
    `\`allow_implicit_invocation: false\` (see agents/openai.yaml next to this file) so Codex never fires it on its own` ,
    `judgment, matching the original command's user-only invocation.`,
  ];
  if (cmd.data["argument-hint"]) trigger.push(``, `Original arguments: \`${cmd.data["argument-hint"]}\` — Codex has no positional/named $ARGUMENTS substitution, so type these directly after \`$${skillName}\` as free text instead.`);
  const body = rewriteSkillRefs(cmd.body, { displayPrefix: DISPLAY_PREFIX, hrefBase: "../" });
  return [...front, ...trigger, ``, body].join("\n");
}

/** Forces explicit-only `$skill-name` invocation — see the file header note. */
function commandSkillPolicyYaml() {
  return `policy:\n  allow_implicit_invocation: false\n`;
}

function mcpConfigToml(mcpServers) {
  const blocks = [];
  for (const [name, cfg] of Object.entries(mcpServers)) {
    const table = [`[mcp_servers.${name}]`];
    if (cfg.command) table.push(`command = ${tomlBasicString(cfg.command)}`);
    if (Array.isArray(cfg.args)) table.push(`args = ${tomlStringArray(cfg.args)}`);
    if (cfg.url) table.push(`url = ${tomlBasicString(cfg.url)}`);
    blocks.push(table.join("\n"));
    if (cfg.env && Object.keys(cfg.env).length) {
      const envTable = [`[mcp_servers.${name}.env]`];
      for (const [k, v] of Object.entries(cfg.env)) envTable.push(`${k} = ${tomlBasicString(v)}`);
      blocks.push(envTable.join("\n"));
    }
  }
  return blocks.join("\n\n") + "\n";
}

function buildAgentsMd(scanned) {
  const parts = [];
  parts.push(`# AGENTS.md`, ``, `> Generated by \`ck convert codex\` from this project's \`.claude/\` configuration. Re-run the command after editing the source to refresh.`, ``);
  if (scanned.claudeMd) {
    parts.push(rewriteSkillRefs(scanned.claudeMd, { displayPrefix: DISPLAY_PREFIX, hrefBase: DISPLAY_PREFIX }));
  }
  if (scanned.workflows.length) {
    parts.push(`## Workflows`, ``, `Full text kept out of this file to stay under Codex's \`project_doc_max_bytes\` (32 KiB default) — open these on demand:`, ``);
    for (const w of scanned.workflows) parts.push(`- [.codex/workflows/${w.file}](.codex/workflows/${w.file})`);
    parts.push(``);
  }
  if (scanned.agents.length) {
    parts.push(`## Agents (\`.codex/agents/*.toml\`)`, ``);
    for (const a of scanned.agents) parts.push(`- **${a.name}** — ${a.data.description || ""}`);
    parts.push(``);
  }
  if (scanned.commands.length) {
    parts.push(`## Slash commands ported to Codex skills (\`.codex/skills/*\`)`, ``, `Explicit-invoke with \`$<name>\` (each ships \`allow_implicit_invocation: false\` so it behaves like the original command — user-triggered only, never Codex's own guess):`, ``);
    for (const c of scanned.commands) parts.push(`- \`$${c.ns}-${c.name}\` — ${c.data.description || ""}`);
    parts.push(``);
  }
  return parts.join("\n");
}

function generate(projectRoot, outRoot, scanned, options = {}) {
  const summary = newSummary();
  const codexDir = path.join(outRoot, ".codex");

  copyDirSafe(projectRoot, scanned.skillsSrc, path.join(codexDir, "skills"), options, summary);

  for (const w of scanned.workflows) {
    const content = rewriteSkillRefs(w.content, { displayPrefix: DISPLAY_PREFIX, hrefBase: "../skills/" });
    writeFileSafe(projectRoot, path.join(codexDir, "workflows", w.file), content, options, summary);
  }

  for (const agent of scanned.agents) {
    writeFileSafe(projectRoot, path.join(codexDir, "agents", `${agent.name}.toml`), agentToml(agent), options, summary);
  }

  for (const cmd of scanned.commands) {
    const skillName = `${cmd.ns}-${cmd.name}`;
    const skillDir = path.join(codexDir, "skills", skillName);
    writeFileSafe(projectRoot, path.join(skillDir, "SKILL.md"), commandSkillMd(cmd), options, summary);
    writeFileSafe(projectRoot, path.join(skillDir, "agents", "openai.yaml"), commandSkillPolicyYaml(), options, summary);
  }

  if (scanned.mcpServers) {
    writeFileSafe(projectRoot, path.join(codexDir, "config.toml"), mcpConfigToml(scanned.mcpServers), options, summary);
  }

  writeFileSafe(projectRoot, path.join(outRoot, "AGENTS.md"), buildAgentsMd(scanned), options, summary);

  summary.warnings.push("hooks/ and settings.json (permissions, statusline) have no Codex CLI equivalent — not converted.");
  if (scanned.agents.length) summary.warnings.push("Agent `tools:` lists were dropped — Claude Code tool names (Read, Edit, Bash...) don't map to Codex tool ids; review .codex/agents/*.toml and set sandbox_mode / tool access manually if needed.");
  return summary;
}

module.exports = { generate };
